    private void btnMusicItemManageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMusicItemManageActionPerformed
           String title = txtMusicTitleManage.getText().trim();
        String artist = txtMusicArtistManage.getText().trim();
        String genre = cmbMusicGenreManage.getSelectedItem().toString();
        String format = cmbboxMusicFormateManage.getSelectedItem().toString();
        String priceStr = txtMusicItemPriceManage.getText().trim();
        String quantityStr = txtMusicQuantityManage.getText().trim();
        String yearStr = txtMusicReleaseYearManage.getText().trim();
        String description = txtMusicDescriptionManage.getText().trim();

        // 1. Validation checks
        if (title.isEmpty() || artist.isEmpty() || genre.equals("Select Genre") || format.equals("Select Formate")) {
            JOptionPane.showMessageDialog(this, "Please fill in all required fields and select valid dropdown options.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double price = Double.parseDouble(priceStr);
            int quantity = Integer.parseInt(quantityStr);
            int releaseYear = Integer.parseInt(yearStr);

            // Updated column name in UPDATE query: stock_quantity = ?
            String updateQuery = "UPDATE music_items SET artist = ?, genre = ?, format = ?, price = ?, stock_quantity = ?, release_year = ?, description = ? WHERE title = ?";

            try (Connection conn = DBConnection.getConnection();
                 PreparedStatement pstmt = conn.prepareStatement(updateQuery)) {

                pstmt.setString(1, artist);
                pstmt.setString(2, genre);
                pstmt.setString(3, format);
                pstmt.setDouble(4, price);
                pstmt.setInt(5, quantity); // Maps to stock_quantity column
                pstmt.setInt(6, releaseYear);
                pstmt.setString(7, description);
                pstmt.setString(8, title);

                int rowsAffected = pstmt.executeUpdate();

                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(this, "Music item updated successfully!", "Update Successful", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Update failed. No item found with title: " + title, "Update Failed", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Price, Quantity, and Release Year must be valid numbers.", "Invalid Format", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }   
    }//GEN-LAST:event_btnMusicItemManageActionPerformed

