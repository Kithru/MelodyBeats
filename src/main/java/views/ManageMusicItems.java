    private void btnManageItemSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnManageItemSearchActionPerformed
        String searchText = txtMusicTitleManage.getText().trim();

        if (searchText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a value, letter, or word to search.", "Input Required", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Uses LIKE %?% for partial string matching
        String query = "SELECT * FROM music_items WHERE title LIKE ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            // % surrounding the search string allows matching anywhere in the text
            pstmt.setString(1, "%" + searchText + "%");
            ResultSet rs = pstmt.executeQuery();

            if (rs.next()) {
                // Fills fields with the first matching record
                txtMusicTitleManage.setText(rs.getString("title")); // Full title display
                txtMusicArtistManage.setText(rs.getString("artist"));
                cmbMusicGenreManage.setSelectedItem(rs.getString("genre"));
                cmbboxMusicFormateManage.setSelectedItem(rs.getString("format"));
                txtMusicItemPriceManage.setText(String.valueOf(rs.getDouble("price")));
                txtMusicQuantityManage.setText(String.valueOf(rs.getInt("stock_quantity"))); 
                txtMusicReleaseYearManage.setText(String.valueOf(rs.getInt("release_year")));
                txtMusicDescriptionManage.setText(rs.getString("description"));

                JOptionPane.showMessageDialog(this, "Record found!", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "No matching music item found for: " + searchText, "Not Found", JOptionPane.ERROR_MESSAGE);
                clearFieldsExceptTitle();
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnManageItemSearchActionPerformed

